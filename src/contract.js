// Builds the API contract the app currently expects: Phase 1 plus the Phase 2
// features that are turned on. Shown in Lab → API contract.

import { FEATURES, RESOURCE } from './features'

const MAX_YEAR = new Date().getFullYear() + 5

const featureTitle = (key) => FEATURES.find((f) => f.key === key)?.title

const json = (value) => JSON.stringify(value, null, 2)

function itemFields(f) {
  return [
    { name: 'id', type: 'int', rule: 'Generated by the API' },
    { name: 'title', type: 'string', rule: 'Required, max 120 characters' },
    { name: 'year', type: 'int | null', rule: `Optional, 1888..${MAX_YEAR}` },
    { name: 'genre', type: 'string', rule: 'Optional' },
    { name: 'posterUrl', type: 'string', rule: 'Optional, image URL' },
    { name: 'notes', type: 'string', rule: 'Optional' },
    { name: 'watched', type: 'bool', rule: 'Defaults to false' },
    f.ratings && { name: 'rating', type: 'int | null', rule: 'Optional, 1..5', feature: 'ratings' },
  ].filter(Boolean)
}

function exampleItem(f, overrides = {}) {
  return {
    id: 1,
    title: 'Dune: Part Two',
    year: 2024,
    genre: 'Sci-Fi',
    posterUrl: '',
    notes: '',
    watched: false,
    ...(f.ratings ? { rating: 5 } : {}),
    ...overrides,
  }
}

function exampleInput(f) {
  const { id: _id, ...input } = exampleItem(f)
  return input
}

const NOT_FOUND = {
  status: 404,
  description: 'No item with this id',
  example: json({
    type: 'https://tools.ietf.org/html/rfc9110#section-15.5.5',
    title: 'Not Found',
    status: 404,
    traceId: '00-…',
  }),
}

const VALIDATION_ERROR = {
  status: 400,
  description: 'Invalid body. The app shows these errors in the form.',
  example: json({
    type: 'https://tools.ietf.org/html/rfc9110#section-15.5.1',
    title: 'One or more validation errors occurred.',
    status: 400,
    errors: {
      Title: ['The Title field is required.'],
      Year: [`The field Year must be between 1888 and ${MAX_YEAR}.`],
    },
    traceId: '00-…',
  }),
}

export function buildContract(f) {
  const item = exampleItem(f)

  const endpoints = [
    {
      method: 'GET',
      path: RESOURCE,
      summary: f.filtering ? 'List items, optionally filtered' : 'List all items',
      query: f.filtering
        ? [
            { name: 'q', type: 'string', rule: 'Case-insensitive match on title (and genre)' },
            { name: 'watched', type: 'bool', rule: 'true | false' },
          ]
        : null,
      queryFeature: f.filtering ? 'filtering' : null,
      queryNote: f.filtering ? 'Every param is optional. An omitted param means "don\'t filter by it".' : null,
      example: f.filtering ? `GET ${RESOURCE}?q=dune&watched=false` : null,
      responses: [{ status: 200, description: 'Array of items (can be empty)', example: json([item]) }],
    },
    f.stats && {
      method: 'GET',
      path: `${RESOURCE}/stats`,
      summary: 'Summary of the watchlist',
      feature: 'stats',
      responses: [
        {
          status: 200,
          description: 'averageRating is null when nothing is rated',
          example: json({
            total: 14,
            watched: 8,
            unwatched: 6,
            averageRating: f.ratings ? 4.6 : null,
          }),
        },
      ],
    },
    {
      method: 'GET',
      path: `${RESOURCE}/{id}`,
      summary: 'Get one item',
      note: 'Not called by the app, but part of the CRUD.',
      responses: [{ status: 200, description: 'The item', example: json(item) }, NOT_FOUND],
    },
    {
      method: 'POST',
      path: RESOURCE,
      summary: 'Create an item',
      body: json(exampleInput(f)),
      responses: [
        { status: 201, description: 'The created item, with its new id', example: json(item) },
        VALIDATION_ERROR,
      ],
    },
    {
      method: 'PUT',
      path: `${RESOURCE}/{id}`,
      summary: 'Replace an item',
      note: f.patch
        ? 'Used by the edit form.'
        : `Used by the edit form, "Mark as watched"${f.ratings ? ' and the stars' : ''} (the whole item is sent).`,
      body: json({ ...exampleInput(f), watched: true }),
      responses: [
        { status: 200, description: 'The updated item', example: json(exampleItem(f, { watched: true })) },
        VALIDATION_ERROR,
        NOT_FOUND,
      ],
    },
    f.patch && {
      method: 'PATCH',
      path: `${RESOURCE}/{id}`,
      summary: 'Change only some fields',
      feature: 'patch',
      note: `Used by "Mark as watched"${f.ratings ? ' and the stars' : ''}. Fields not in the body stay unchanged.`,
      body: json({ watched: true }),
      responses: [
        { status: 200, description: 'The full, updated item', example: json(exampleItem(f, { watched: true })) },
        VALIDATION_ERROR,
        NOT_FOUND,
      ],
    },
    {
      method: 'DELETE',
      path: `${RESOURCE}/{id}`,
      summary: 'Delete an item',
      responses: [{ status: 204, description: 'No body' }, NOT_FOUND],
    },
  ].filter(Boolean)

  return { fields: itemFields(f), endpoints, featureTitle }
}
